// English root HTML is the source. Generate checked-in Chinese HTML without a
// runtime translation service, duplicated experiment code, or a deployment build.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export const pageFiles = ['index.html', 'documentation.html', 'phase-swap.html', 'color-phase.html', 'filtering.html', 'region-swap.html', 'spectrum.html'];
const root = new URL('../', import.meta.url);
const normalize = text => text.trim().replace(/\s+/g, ' ');
export function transformHTML(html, translate, chinese = false) {
  const stack = [];
  const voidTags = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr']);
  return html.replace(/<!--[\s\S]*?-->|<![^>]*>|<\/?[A-Za-z][^>]*>|[^<]+/g, token => {
    if (token.startsWith('<!--') || token.startsWith('<!')) return token;
    if (token.startsWith('</')) { stack.pop(); return token; }
    if (token.startsWith('<')) {
      const tag = token.match(/^<([\w-]+)/)[1].toLowerCase();
      const skip = stack.at(-1)?.skip || ['script', 'style'].includes(tag) || /\bdata-math\b/.test(token);
      const description = tag === 'meta' && /name="description"/.test(token);
      let result = token.replace(/\b(aria-label|title|alt|content)="([^"]*)"/g, (match, attr, value) => {
        if (attr === 'content' && !description) return match;
        const key = normalize(value);
        return key ? `${attr}="${translate(key).replace(/"/g, '&quot;')}"` : match;
      });
      if (chinese) result = result.replace(/\blang="[^"]*"/g, 'lang="zh-TW"');
      if (chinese) result = result.replace(/\b(src|href)="\.\/([^"#]+)"/g, (match, attr, path) => {
        return attr === 'src' || /^(?:assets\/|js\/|favicon\.svg$|LICENSE$)|\.css$/.test(path) ? `${attr}="../${path}"` : match;
      });
      if (!voidTags.has(tag)) stack.push({ tag, skip });
      return result;
    }
    if (stack.at(-1)?.skip || !normalize(token) || !/[A-Za-z\u3400-\u9fff]/.test(token)) return token;
    const key = normalize(token);
    return token.replace(token.trim(), translate(key));
  });
}

export async function build({ check = false } = {}) {
  const translations = JSON.parse(await readFile(new URL('content/zh-TW.json', root), 'utf8'));
  const missing = new Set();
  const translate = key => { if (!Object.hasOwn(translations, key)) missing.add(key); return translations[key] ?? key; };
  await mkdir(new URL('zh/', root), { recursive: true });
  let stale = false;
  for (const file of pageFiles) {
    const source = (await readFile(new URL(file, root), 'utf8')).replace(/\r\n/g, '\n');
    const generated = '<!-- Generated by scripts/build-locales.mjs from English HTML and content/zh-TW.json. -->\n' + transformHTML(source, translate, true);
    const target = new URL(`zh/${file}`, root);
    if (check) {
      const actual = (await readFile(target, 'utf8').catch(() => '')).replace(/\r\n/g, '\n');
      if (actual !== generated) { console.error(`Out of date: zh/${file}`); stale = true; }
    } else await writeFile(target, generated);
  }
  if (missing.size) throw new Error(`Missing Chinese translations:\n${[...missing].join('\n')}`);
  if (stale) throw new Error('Run node scripts/build-locales.mjs to update Chinese pages.');
  return pageFiles.length;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`${await build({ check: process.argv.includes('--check') })} Chinese pages ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
}
